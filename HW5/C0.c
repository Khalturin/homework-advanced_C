#include <stdio.h>
#include <string.h>

int count_unique_3digit_combinations(const char *s, size_t len) {    
    // Если цифр меньше 3, трехзначное число получить невозможно
    if (len < 3) 
        return 0;

    // Массив для отслеживания встреченных чисел.
    // Индекс соответствует самому числу (0..999).
    // Инициализируется нулями.
    int seen[1000] = {0};
    
    int count = 0;

    // Перебираем все комбинации из 3 цифр с сохранением порядка
    // i - индекс первой цифры (сотни)
    // j - индекс второй цифры (десятки)
    // k - индекс третьей цифры (единицы)
    for (int i = 0; i < len - 2; i++) {
        // Первая цифра не может быть '0', иначе число не трехзначное
        if (s[i] == '0') {
            continue;
        }
        for (int j = i + 1; j < len - 1; j++) {
            for (int k = j + 1; k < len; k++) {
                // Формируем число из выбранных цифр
                int val = (s[i] - '0') * 100 + 
                          (s[j] - '0') * 10 + 
                          (s[k] - '0');
                
                // Если это число еще не встречалось, учитываем его
                if (!seen[val]) {
                    seen[val] = 1;
                    count++;
                }
            }
        }
    }
    return count;
}

int main() {
    // Буфер для хранения числа в виде строки. 
    // 256 символов достаточно для большинства задач, 
    // но можно увеличить при необходимости.
    char s[256];
    
    // Считываем число как строку
    if (scanf("%255s", s) != 1) {
        return 0;
    }

    size_t len = strlen(s);
    int count = count_unique_3digit_combinations(s, len);
    
    printf("%d\n", count);
}