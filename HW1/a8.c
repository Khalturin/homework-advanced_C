/*
 * Весы
 * В стартер боксе Geek Brains есть электронные чашечные весы (вместимость каждой чашки 1 тонна) и гири массами 1г, 3г, 9г, 27г, и т.д. по одной штуке каждой массы. Менеджер из рекламного отдела взял такие весы и не знает, можно ли взвесить что-нибудь тяжелое и если можно, сколько гирь придется положить на весы (на любую чашку). Надо помочь ему. Формат входных данных: единственное натуральное число – масса взвешиваемого товара в граммах (не больше 1000000000). Формат выходных данных: единственное целое число – общее количество гирь или число –1 если данный товар взвесить невозможно.
*/

#include <stdio.h>
#include <stdint.h>

int count_kettlebell(uint32_t weight){
    if(weight > 1000000)
        return -1;
    int count = 0;
    uint32_t value = weight;
    long long power = 1; // текущая степень 3^k
    long long sum_left = 0;   // гири на чаше с товаром (коэф -1)
    long long sum_right = 0;  // гири на противоположной чаше (коэф +1)

    while (value != 0) {
        long long r = value % 3;
        if (r == 0) {
            // digit 0 — не используем гирю
        } else if (r == 1) {
            // digit +1 → гиря на правой чаше
            sum_right += power;
            count++;
        } else if (r == 2) {
            // digit -1 → гиря на левой чаше
            sum_left += power;
            count++;
            value += 1; // компенсация
        }
        value /= 3;
        power *= 3;
    }

    // Проверка ограничений вместимости чаш
    if (weight + sum_left <= 1000000LL && sum_right <= 1000000LL) {
        return count;
    } else {
        return -1;
    }
}

int main() {
    uint32_t val = 0;
    scanf("%u", &val);
    printf("%d\n", count_kettlebell(val));
    return 0;
}